// Generate a SLEIGH include that gives every `ex9.it N` the semantics of EX9 table entry N.
// Run headless on a program loaded with the stock NDS32:LE:32:default language.
// Script args: <itb hex address> <output .sinc path>
// @category MT7961

import java.io.PrintWriter;
import java.util.*;

import ghidra.app.script.GhidraScript;
import ghidra.program.model.address.Address;
import ghidra.program.model.lang.Language;
import ghidra.program.model.lang.Register;
import ghidra.program.model.listing.Instruction;
import ghidra.program.model.pcode.PcodeOp;
import ghidra.program.model.pcode.Varnode;

public class Ex9Gen extends GhidraScript {

	private Language lang;
	private Set<Long> declared;

	@Override
	protected void run() throws Exception {
		String[] args = getScriptArgs();
		Address itb = toAddr(Long.decode(args[0]));
		lang = currentProgram.getLanguage();
		int ok = 0, branch = 0, skipped = 0;
		try (PrintWriter out = new PrintWriter(args[1])) {
			out.println("# Generated by Ex9Gen.java for MT7961 WIFI_RAM_CODE, ITB=" + itb);
			out.println("# One constructor per EX9 index; unmatched entries fall back to the generic ex9 pcodeop.");
			for (int i = 0; i < 512; i++) {
				Address a = itb.add(4L * i);
				clearListing(a, a.add(3));
				disassemble(a);
				Instruction ins = getInstructionAt(a);
				if (ins == null || ins.getLength() != 4) {
					out.println("# " + i + ": not a 32-bit instruction, skipped");
					skipped++;
					continue;
				}
				String text = ins.toString().replace("\"", "'");
				String constraint = i < 32
						? "$(I16) & opc10=0b1011101010 & imm5u=" + i
						: "$(I16) & opc6=0b110101 & imm4u=" + (i >> 5) + " & imm5u=" + (i & 31);
				String mn = ins.getMnemonicString().toLowerCase();
				if (mn.equals("jal") || mn.equals("j")) {
					// NDS32 stores 32-bit instructions big-endian regardless of data endianness
					byte[] b = getBytes(a, 4);
					long word = ((b[0] & 0xffL) << 24) | ((b[1] & 0xffL) << 16) | ((b[2] & 0xffL) << 8) | (b[3] & 0xffL);
					long low = (word & 0xffffffL) << 1;
					String dst = "ex9dst" + i;
					out.printf("%s: tgt is epsilon [ tgt = (inst_start & 0xfe000000) | 0x%x; ] { export *[ram]:4 tgt; }%n",
						dst, low);
					out.printf(":ex9.it \"#%d\" is %s & %s { %s }  # %s%n", i, constraint, dst,
						mn.equals("jal") ? "lp = inst_next; call " + dst + ";" : "goto " + dst + ";", text);
					branch++;
					continue;
				}
				String body = translate(ins.getPcode());
				if (body == null) {
					out.println("# " + i + ": untranslatable p-code for '" + text + "', generic fallback");
					skipped++;
					continue;
				}
				out.printf(":ex9.it \"#%d\" is %s { %s }  # %s%n", i, constraint, body, text);
				ok++;
			}
		}
		println(String.format("ex9: %d translated, %d branches, %d skipped", ok, branch, skipped));
	}

	private String translate(PcodeOp[] ops) {
		declared = new HashSet<>();
		StringBuilder sb = new StringBuilder();
		for (PcodeOp op : ops) {
			String s = stmt(op);
			if (s == null) {
				return null;
			}
			sb.append(s).append(' ');
		}
		return sb.toString().trim();
	}

	private String vn(Varnode v) {
		if (v.isConstant()) {
			return String.format("0x%x:%d", v.getOffset(), v.getSize());
		}
		if (v.isRegister()) {
			Register r = lang.getRegister(v.getAddress(), v.getSize());
			return r == null ? null : r.getName();
		}
		if (v.isUnique()) {
			return "u" + Long.toHexString(v.getOffset());
		}
		if (v.isAddress()) {
			return String.format("*[%s]:%d 0x%x:4", v.getAddress().getAddressSpace().getName(), v.getSize(),
				v.getOffset());
		}
		return null;
	}

	private String lhs(Varnode v) {
		String n = vn(v);
		if (n != null && v.isUnique() && declared.add(v.getOffset())) {
			return "local " + n + ":" + v.getSize();
		}
		return n;
	}

	private static final Map<Integer, String> BIN = Map.ofEntries(
		Map.entry(PcodeOp.INT_ADD, "+"), Map.entry(PcodeOp.INT_SUB, "-"), Map.entry(PcodeOp.INT_MULT, "*"),
		Map.entry(PcodeOp.INT_DIV, "/"), Map.entry(PcodeOp.INT_SDIV, "s/"), Map.entry(PcodeOp.INT_REM, "%"),
		Map.entry(PcodeOp.INT_SREM, "s%"), Map.entry(PcodeOp.INT_AND, "&"), Map.entry(PcodeOp.INT_OR, "|"),
		Map.entry(PcodeOp.INT_XOR, "^"), Map.entry(PcodeOp.INT_LEFT, "<<"), Map.entry(PcodeOp.INT_RIGHT, ">>"),
		Map.entry(PcodeOp.INT_SRIGHT, "s>>"), Map.entry(PcodeOp.INT_EQUAL, "=="),
		Map.entry(PcodeOp.INT_NOTEQUAL, "!="), Map.entry(PcodeOp.INT_LESS, "<"),
		Map.entry(PcodeOp.INT_SLESS, "s<"), Map.entry(PcodeOp.INT_LESSEQUAL, "<="),
		Map.entry(PcodeOp.INT_SLESSEQUAL, "s<="), Map.entry(PcodeOp.BOOL_AND, "&&"),
		Map.entry(PcodeOp.BOOL_OR, "||"), Map.entry(PcodeOp.BOOL_XOR, "^^"));

	private static final Map<Integer, String> FN = Map.of(
		PcodeOp.INT_ZEXT, "zext", PcodeOp.INT_SEXT, "sext", PcodeOp.INT_CARRY, "carry",
		PcodeOp.INT_SCARRY, "scarry", PcodeOp.INT_SBORROW, "sborrow", PcodeOp.POPCOUNT, "popcount",
		PcodeOp.LZCOUNT, "lzcount");

	private String stmt(PcodeOp op) {
		int oc = op.getOpcode();
		Varnode out = op.getOutput();
		String[] in = new String[op.getNumInputs()];
		for (int k = 0; k < in.length; k++) {
			in[k] = vn(op.getInput(k));
		}
		String rhs;
		switch (oc) {
			case PcodeOp.STORE: {
				String sp = currentProgram.getAddressFactory()
						.getAddressSpace((int) op.getInput(0).getOffset()).getName();
				return in[1] == null || in[2] == null ? null
						: String.format("*[%s]:%d %s = %s;", sp, op.getInput(2).getSize(), in[1], in[2]);
			}
			case PcodeOp.LOAD: {
				String sp = currentProgram.getAddressFactory()
						.getAddressSpace((int) op.getInput(0).getOffset()).getName();
				rhs = in[1] == null ? null : String.format("*[%s]:%d %s", sp, out.getSize(), in[1]);
				break;
			}
			case PcodeOp.COPY:
				rhs = in[0];
				break;
			case PcodeOp.INT_NEGATE:
				rhs = in[0] == null ? null : "~" + in[0];
				break;
			case PcodeOp.INT_2COMP:
				rhs = in[0] == null ? null : "-" + in[0];
				break;
			case PcodeOp.BOOL_NEGATE:
				rhs = in[0] == null ? null : "!" + in[0];
				break;
			case PcodeOp.SUBPIECE:
				rhs = in[0] == null ? null : String.format("%s(%d)", in[0], op.getInput(1).getOffset());
				break;
			case PcodeOp.CALLOTHER: {
				String name = lang.getUserDefinedOpName((int) op.getInput(0).getOffset());
				StringJoiner j = new StringJoiner(", ");
				for (int k = 1; k < in.length; k++) {
					if (in[k] == null) {
						return null;
					}
					j.add(in[k]);
				}
				rhs = name + "(" + j + ")";
				if (out == null) {
					return rhs + ";";
				}
				break;
			}
			default:
				if (BIN.containsKey(oc) && in.length == 2 && in[0] != null && in[1] != null) {
					rhs = in[0] + " " + BIN.get(oc) + " " + in[1];
				}
				else if (FN.containsKey(oc) && Arrays.stream(in).allMatch(Objects::nonNull)) {
					rhs = FN.get(oc) + "(" + String.join(", ", in) + ")";
				}
				else {
					return null; // branches, floats, anything unexpected
				}
		}
		if (rhs == null || out == null) {
			return null;
		}
		String l = lhs(out);
		return l == null ? null : l + " = " + rhs + ";";
	}
}
